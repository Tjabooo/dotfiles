#!/usr/bin/env python3
"""EVA unit-01 activation intro for the GRUB theme: the board powers up before the menu.

    python3 ~/.local/share/neon/grub-theme/intro.py [--preview]

Run build.py first (this reuses its scene() and checks against its background.png).
Writes magi-neon/intro/NN.png (full 2880x1800 frames) and magi-neon/intro.cfg, which
/etc/grub.d/05_unit01_intro sources before the menu entries. The last frame is background.png
itself, so the menu appears on exactly the picture the intro ends on.

Storyboard: frame and header draw in, the card opens on 起動 ACTIVATION, the sync ring sweeps
in, then ENTRY PLUG, LCL, A10 NERVE and UMBILICAL come online one by one (dim -> solid green
起動 flash -> 正常 stamp) while their rows land in the card and the sync ratio climbs, the
harmonics traces lock together at 41.3 %, and the card turns into the boot menu.

GRUB can't animate, so intro.cfg flips full-screen frames: background_image + clear
(clear forces gfxterm to repaint) and a silent `play` note as a millisecond pause
(`sleep` only does whole seconds). Every frame also costs a PNG decode, estimated as
DECODE_MS and subtracted from the pause. Any key fast-forwards the pauses; holding Shift
skips the rest of the intro. play/png/gfxterm_background/keystatus are in the signed
grubx64.efi (grub-install-signed's module list), so nothing needs rebuilding or re-signing.
--preview writes intro-preview.mp4 with the planned timing.
"""
import importlib.util
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("grub_theme_build", HERE / "build.py")
g = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(g)

OUT = g.OUT
FRAMES = OUT / "intro"
THEME = "magi-neon"
DECODE_MS = 80           # GUESS for GRUB's cost per 2880x1800 PNG (load + repaint); recalibrate on a real boot
PACE = 1.4               # stretch every hold (magi's first real boot was "a little fast" at 1.0)

ROWS = [(("挿入", "ENTRY PLUG"), "INSERTED"), (("注水", "LCL"), "FILLED"),
        (("接続", "A10 NERVE"), "CONNECTED"), (("電源", "UMBILICAL"), "EXTERNAL")]
SYNC_STEPS = (9.6, 19.8, 30.2, 38.7)


def storyboard():
    S = dict(glow=0, title=False, htext=False, rule=0, footer=False, brackets=0, card="none", hints=False,
             ring=0, sync=0.0, core=0, links=0, chips=[0, 0, 0, 0], harm=0, converge=0, verdict=None,
             log=[], online=0)
    frames = []

    def shot(ms, **kw):
        S.update(kw)
        frames.append(({k: (list(v) if isinstance(v, list) else v) for k, v in S.items()}, ms))

    shot(350)
    shot(70, brackets=0.5)
    shot(70, brackets=1, rule=0.4)
    shot(100, rule=1, title=True)
    shot(160, htext="intro", footer=True)
    shot(90, glow=0.35, card="frame")
    shot(90, glow=0.7)
    shot(300, glow=1, card="boot")
    shot(70, ring=0.35)
    shot(70, ring=0.7)
    shot(240, ring=1, core=1)
    log = []
    for i in range(4):
        chips = list(S["chips"])
        chips[i] = 1
        log.append([ROWS[i][0], "LOADING"])
        shot(170, links=i + 1, chips=chips, log=[list(r) for r in log])
        chips[i] = 2
        log[-1][1] = ROWS[i][1]
        shot(110, chips=list(chips), log=[list(r) for r in log])
        chips[i] = 3
        shot(170, chips=list(chips), online=i + 1, sync=SYNC_STEPS[i],
             verdict=(f"{i + 1} / 4", "  SYSTEMS ONLINE" if i < 3 else "  SYSTEMS ONLINE  ·  SYNCHRONIZING"))
    shot(90, harm=0.5)
    shot(120, harm=1)
    shot(120, converge=0.5, sync=40.4)
    log.append([("同期", "SYNC RATIO"), "41.3 %"])
    shot(600, converge=1, sync=g.SYNC, core=2, card="done", log=[list(r) for r in log],
         verdict=("4 / 4", "  SYSTEMS NORMAL  ·  LAUNCH AUTHORIZED"))
    shot(220, hints=True)
    shot(0, card="final", log=[], htext="final")          # == background.png
    return frames


def write_cfg(frames):
    root = f"($root)/grub/themes/{THEME}"
    lines = [
        "# EVA unit-01 activation intro. Generated by ~/.local/share/neon/grub-theme/intro.py; edit that.",
        "# Sourced by /etc/grub.d/05_unit01_intro before the menu. Hold Shift to skip, any key fast-forwards.",
        "if [ \"$unit01_intro\" != done ]; then",
        "  set unit01_intro=done",
        "  set unit01_skip=0",
        "  set color_normal=black/black",
    ]
    for i, (_, ms) in enumerate(frames[:-1]):          # the last frame is background.png, loaded below
        rest = max(0, round(ms * PACE) - DECODE_MS)
        lines.append("  if [ $unit01_skip = 0 ]; then")
        lines.append(f"    background_image {root}/intro/{i:02d}.png")
        lines.append("    clear")
        if rest:
            lines.append(f"    play 60000 0 {rest}")
        lines.append("    if keystatus --shift; then set unit01_skip=1; fi")
        lines.append("  fi")
    lines += [
        "  # skipped or not, end on the menu's own background (also what stays up while the kernel loads)",
        f"  background_image {root}/background.png",
        "  clear",
        "  set color_normal=light-gray/black",
        "fi",
        "# The menu runs its text terminal (console, editor, and the screen while an entry loads) in the",
        "# theme's terminal box and draws this image from the box's corner, unscaled: a crop of the",
        "# background at exactly that box, so the box is invisible against the screen. No clear here:",
        "# it is first drawn inside the box, never full-screen.",
        f"background_image -m normal {root}/terminal-bg.png",
    ]
    (OUT / "intro.cfg").write_text("\n".join(lines) + "\n")


def terminal_rect():
    """The gfxterm window gfxmenu sets up from theme.txt (terminal-left/top/width/height)."""
    spec = {}
    for line in (OUT / "theme.txt").read_text().splitlines():
        k, _, v = line.partition(":")
        if k.strip() in ("terminal-left", "terminal-top", "terminal-width", "terminal-height"):
            spec[k.strip()] = v.strip().strip('"')

    def ev(v, total):
        if "%" in v:
            pct, _, rest = v.partition("%")
            return g.grub_px(int(pct), int(rest or 0), total)
        return int(v)
    return (ev(spec["terminal-left"], g.FW), ev(spec["terminal-top"], g.FH),
            ev(spec["terminal-width"], g.FW), ev(spec["terminal-height"], g.FH))


def main():
    bg_path = OUT / "background.png"
    assert bg_path.exists(), "run build.py first"
    frames = storyboard()
    if FRAMES.exists():
        shutil.rmtree(FRAMES)
    FRAMES.mkdir()
    bg = Image.open(bg_path).convert("RGB")
    final = g.scene(frames[-1][0])
    diff = np.abs(np.asarray(final).astype(int) - np.asarray(bg).astype(int))
    print(f"last intro frame vs background.png: max diff {diff.max()}, pixels off {(diff.max(axis=2) > 0).sum()}")
    imgs = []
    for i, (S, ms) in enumerate(frames):
        if i == len(frames) - 1:
            im = bg                                           # intro.cfg ends on background.png itself
        else:
            im = g.scene(S)
            im.save(FRAMES / f"{i:02d}.png", optimize=True)
        imgs.append((im, ms))
    write_cfg(frames)
    tx, ty, tw, th = terminal_rect()
    bg.crop((tx, ty, tx + tw, ty + th)).save(OUT / "terminal-bg.png", optimize=True)
    print(f"terminal box {tw}x{th}+{tx}+{ty} -> terminal-bg.png")
    total = sum(max(round(ms * PACE), DECODE_MS) for _, ms in frames)
    size = sum(f.stat().st_size for f in FRAMES.iterdir())
    print(f"{len(frames)} frames, {size / 1e6:.1f} MB, ~{total / 1000:.1f} s at {DECODE_MS} ms/frame decode")
    if "--preview" in sys.argv:
        pv = HERE / "intro-preview"
        if pv.exists():
            shutil.rmtree(pv)
        pv.mkdir()
        n = 0
        for im, ms in imgs + [(imgs[-1][0], 1500)]:
            small = im.resize((1440, 900), Image.LANCZOS)
            for _ in range(max(1, round(max(ms * PACE, DECODE_MS) / 1000 * 30))):
                small.save(pv / f"{n:04d}.png")
                n += 1
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-framerate", "30", "-i", str(pv / "%04d.png"), "-c:v", "libx264",
                        "-pix_fmt", "yuv420p", "-crf", "18", str(HERE / "intro-preview.mp4")], check=True)
        shutil.rmtree(pv)


if __name__ == "__main__":
    main()
